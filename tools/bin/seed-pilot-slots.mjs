#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractImageTags, resolveRef, isChrome, slotIdFor, labelFor } from '../src/parse.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

export const PILOT_PAGES = [
  'index.html',
  'pages/about/OurManagement.html',
  'pages/about/OurFounder.html',
  'pages/about/PrincipalMessage.html',
  'pages/about/FIH.html',
];

const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * Wrap every live, non-chrome image on the page in a sentinel pair and add its
 * data-vhs-slot marker. Tags already carrying the marker are left alone, which
 * makes the script idempotent.
 */
export function planPage(html, pageRepoPath) {
  const tags = extractImageTags(html);
  const slots = [];
  const edits = [];
  let n = 0;

  for (const t of tags) {
    if (t.tag.includes('data-vhs-slot=')) {
      n += 1; // already seeded — keep numbering aligned
      continue;
    }
    const repoPath = resolveRef(pageRepoPath, t.src);
    if (!repoPath || isChrome(repoPath)) continue;

    n += 1;
    const id = slotIdFor(pageRepoPath, n);
    slots.push({
      id,
      pagePath: pageRepoPath,
      label: labelFor(pageRepoPath, n),
      originalSrc: t.src,
      alt: t.alt,
    });

    // The parser matches <img case-insensitively, so preserve whatever case was
    // actually matched instead of hardcoding lowercase.
    const withMarker = t.tag.replace(/<img\b/i, (m) => `${m} data-vhs-slot="${id}"`);
    edits.push({
      index: t.index,
      length: t.tag.length,
      replacement: `<!--vhs:begin ${id}-->${withMarker}<!--vhs:end ${id}-->`,
    });
  }

  // Apply back-to-front so earlier offsets stay valid.
  let rewritten = html;
  for (const e of edits.slice().reverse()) {
    rewritten = rewritten.slice(0, e.index) + e.replacement + rewritten.slice(e.index + e.length);
  }
  return { rewritten, slots };
}

function main() {
  const apply = process.argv.includes('--apply');
  const allSlots = [];

  for (const page of PILOT_PAGES) {
    const abs = join(REPO, page);
    const html = readFileSync(abs, 'utf8');
    const { rewritten, slots } = planPage(html, page);
    allSlots.push(...slots);
    console.log(`${page}: ${slots.length} slot(s)`);
    for (const s of slots) console.log(`    ${s.id}  ${s.originalSrc}`);
    if (apply && rewritten !== html) writeFileSync(abs, rewritten);
  }

  const lines = allSlots.map(
    (s) =>
      `INSERT INTO slots (id, page_path, label, optional, r2_key, original_src, alt) VALUES (` +
      `${sqlStr(s.id)}, ${sqlStr(s.pagePath)}, ${sqlStr(s.label)}, 0, NULL, ` +
      `${sqlStr(s.originalSrc)}, ${sqlStr(s.alt)});`,
  );
  const sql = `-- Generated by tools/bin/seed-pilot-slots.mjs\n${lines.join('\n')}\n`;

  if (apply) {
    writeFileSync(join(REPO, 'worker', 'migrations', '0003_pilot_slots.sql'), sql);
    console.log(`\nwrote worker/migrations/0003_pilot_slots.sql (${allSlots.length} slots)`);
  } else {
    console.log(`\n--- dry run, ${allSlots.length} slots; pass --apply to write ---`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
